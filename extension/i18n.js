  function make(lang) {
    const d = DICT[lang] || DICT.en;
    const t = (key, params) => {
      let s = d[key] ?? DICT.en[key] ?? key;
      if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
      return s;
    };
    t.lang = DICT[lang] ? lang : 'en';
    t.locale = LOCALES[t.lang];
    return t;
  }

